"""Template code generator used by the Developer agent in MOCK mode.

Turns the architecture's entity list into a small but real FastAPI service
with a pytest suite. The generated code genuinely runs; it is not a stub.
With MOCK_INJECT_DEFECT=true the first version contains one clearly
labelled defect so the review -> correction loop can be demonstrated.
"""

import re
from typing import Any

PY_TYPES = {"str": "str", "int": "int", "float": "float", "bool": "bool", "date": "date"}
SANDBOX_REQUIREMENTS = (
    "fastapi==0.115.6\npydantic==2.10.4\nuvicorn==0.32.1\npytest==8.3.4\nhttpx==0.28.1\n"
)


def snake(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def plural(word: str) -> str:
    if word.endswith("y") and word[-2:-1] not in "aeiou":
        return word[:-1] + "ies"
    if word.endswith(("s", "x", "ch", "sh")):
        return word + "es"
    return word + "s"


def route_for(entity_name: str) -> str:
    return "/api/" + plural(snake(entity_name)).replace("_", "-")


def collection_key(entity_name: str) -> str:
    return plural(snake(entity_name))


def sample_value(field: dict[str, Any]) -> Any:
    name, kind = field["name"], field["type"]
    if kind == "int":
        return 1
    if kind == "float":
        return 10.5
    if kind == "bool":
        return True
    if kind == "date":
        return "2026-01-15"
    if "email" in name:
        return "user@example.com"
    return f"Sample {name.replace('_', ' ')}"


def field_line(field: dict[str, Any]) -> str:
    py_type = PY_TYPES[field["type"]]
    name = field["name"]
    if not field.get("required", True):
        return f"    {name}: {py_type} | None = None"
    if field["type"] == "str":
        return f"    {name}: str = Field(min_length=1, max_length=200)"
    if field["type"] == "int" and name.endswith("_id"):
        return f"    {name}: int = Field(ge=1)"
    if field["type"] in ("int", "float"):
        return f"    {name}: {py_type} = Field(ge=0)"
    return f"    {name}: {py_type}"


def usable_fields(entity: dict[str, Any]) -> list[dict[str, Any]]:
    return [f for f in entity["fields"] if f["name"] != "id"]


def generate_models(entities: list[dict[str, Any]]) -> str:
    lines = [
        '"""Pydantic models: request validation (…Create) and responses (with id)."""',
        "",
        "from datetime import date  # noqa: F401  (used by date fields when present)",
        "",
        "from pydantic import BaseModel, Field  # noqa: F401",
        "",
    ]
    for entity in entities:
        name = entity["name"]
        lines += ["", f"class {name}Create(BaseModel):"]
        description = entity.get("description") or name
        lines.append(f'    """{description}"""')
        lines.append("")
        lines += [field_line(f) for f in usable_fields(entity)]
        lines += ["", "", f"class {name}({name}Create):", "    id: int", ""]
    return "\n".join(lines).rstrip() + "\n"


STORAGE = '''"""Thread-safe in-memory repository (prototype only; use a database in production)."""

from itertools import count
from threading import Lock
from typing import Any


class InMemoryRepository:
    def __init__(self) -> None:
        self._items: dict[int, dict[str, Any]] = {}
        self._ids = count(1)
        self._lock = Lock()

    def list(self) -> list[dict[str, Any]]:
        return list(self._items.values())

    def get(self, item_id: int) -> dict[str, Any] | None:
        return self._items.get(item_id)

    def create(self, data: dict[str, Any]) -> dict[str, Any]:
        with self._lock:
            item = {"id": next(self._ids), **data}
            self._items[item["id"]] = item
            return item

    def update(self, item_id: int, data: dict[str, Any]) -> dict[str, Any] | None:
        with self._lock:
            if item_id not in self._items:
                return None
            item = {"id": item_id, **data}
            self._items[item_id] = item
            return item

    def delete(self, item_id: int) -> bool:
        with self._lock:
            return self._items.pop(item_id, None) is not None

    def count(self) -> int:
        return len(self._items)

    def clear(self) -> None:
        with self._lock:
            self._items.clear()
            self._ids = count(1)
'''


def generate_main(
    title: str, entities: list[dict[str, Any]], include_reports: bool, inject_defect: bool
) -> str:
    imports = ", ".join(f"{e['name']}, {e['name']}Create" for e in entities)
    header = f'"""{title} API.\n\nGenerated by AgentForge AI (mock-mode template generator).'
    if inject_defect:
        header += (
            "\n\n[MOCK DEMO] This version intentionally contains one defect so the review and"
            "\ncorrection workflow can be demonstrated. The next version fixes it."
        )
    out = [
        header + '\n"""',
        "",
        "from fastapi import FastAPI, HTTPException",
        "",
        f"from app.models import {imports}",
        "from app.storage import InMemoryRepository",
        "",
        f'app = FastAPI(title="{title}", version="0.1.0")',
        "",
        "REPOSITORIES: dict[str, InMemoryRepository] = {",
    ]
    out += [f'    "{collection_key(e["name"])}": InMemoryRepository(),' for e in entities]
    out += [
        "}",
        "",
        "",
        '@app.get("/health", tags=["System"])',
        "def health() -> dict:",
        '    return {"status": "ok"}',
    ]
    for index, entity in enumerate(entities):
        name = entity["name"]
        key = collection_key(name)
        fn = snake(name)
        route = route_for(name)
        missing_exc = "HTTPExeption" if inject_defect and index == 0 else "HTTPException"
        out += [
            "",
            "",
            f"# ---- {name} " + "-" * max(1, 60 - len(name)),
            f'@app.post("{route}", response_model={name}, status_code=201, tags=["{name}"])',
            f"def create_{fn}(payload: {name}Create) -> dict:",
            f'    return REPOSITORIES["{key}"].create(payload.model_dump(mode="json"))',
            "",
            "",
            f'@app.get("{route}", response_model=list[{name}], tags=["{name}"])',
            f"def list_{key}() -> list[dict]:",
            f'    return REPOSITORIES["{key}"].list()',
            "",
            "",
            f'@app.get("{route}/{{item_id}}", response_model={name}, tags=["{name}"])',
            f"def get_{fn}(item_id: int) -> dict:",
            f'    item = REPOSITORIES["{key}"].get(item_id)',
            "    if item is None:",
            f'        raise HTTPException(status_code=404, detail="{name} not found")',
            "    return item",
            "",
            "",
            f'@app.put("{route}/{{item_id}}", response_model={name}, tags=["{name}"])',
            f"def update_{fn}(item_id: int, payload: {name}Create) -> dict:",
            f'    item = REPOSITORIES["{key}"].update(item_id, payload.model_dump(mode="json"))',
            "    if item is None:",
            f'        raise HTTPException(status_code=404, detail="{name} not found")',
            "    return item",
            "",
            "",
            f'@app.delete("{route}/{{item_id}}", status_code=204, tags=["{name}"])',
            f"def delete_{fn}(item_id: int) -> None:",
            f'    if not REPOSITORIES["{key}"].delete(item_id):',
            f'        raise {missing_exc}(status_code=404, detail="{name} not found")',
        ]
    if include_reports:
        out += [
            "",
            "",
            '@app.get("/api/reports/summary", tags=["Reports"])',
            "def report_summary() -> dict:",
            '    """Record counts per collection (basis for management reports)."""',
            '    return {"counts": {name: repo.count() for name, repo in REPOSITORIES.items()}}',
        ]
    return "\n".join(out) + "\n"


def py_literal(value: Any) -> str:
    return repr(value)


def generate_tests(entities: list[dict[str, Any]], include_reports: bool) -> str:
    out = [
        '"""API tests generated by AgentForge AI. Run with: python -m pytest"""',
        "",
        "import pytest",
        "from fastapi.testclient import TestClient",
        "",
        "from app.main import REPOSITORIES, app",
        "",
        "client = TestClient(app)",
        "",
        "",
        "@pytest.fixture(autouse=True)",
        "def reset_storage():",
        "    for repository in REPOSITORIES.values():",
        "        repository.clear()",
        "    yield",
        "",
        "",
        "def test_health():",
        '    response = client.get("/health")',
        "    assert response.status_code == 200",
        '    assert response.json() == {"status": "ok"}',
    ]
    for entity in entities:
        name = entity["name"]
        fn = snake(name)
        route = route_for(name)
        fields = usable_fields(entity)
        payload = {f["name"]: sample_value(f) for f in fields}
        const = f"{fn.upper()}_PAYLOAD"
        str_field = next((f["name"] for f in fields if f["type"] == "str" and f["required"]), None)
        update_field = str_field or fields[0]["name"]
        update_value = "Updated value" if str_field else sample_value(fields[0])
        out += [
            "",
            "",
            f"{const} = {py_literal(payload)}",
            "",
            "",
            f"def test_{fn}_create_and_get():",
            f'    created = client.post("{route}", json={const})',
            "    assert created.status_code == 201",
            "    body = created.json()",
            '    assert body["id"] >= 1',
            f'    fetched = client.get(f"{route}/{{body[\'id\']}}")',
            "    assert fetched.status_code == 200",
            "    assert fetched.json() == body",
            "",
            "",
            f"def test_{fn}_list():",
            f'    client.post("{route}", json={const})',
            f'    client.post("{route}", json={const})',
            f'    response = client.get("{route}")',
            "    assert response.status_code == 200",
            "    assert len(response.json()) == 2",
            "",
            "",
            f"def test_{fn}_update():",
            f'    item_id = client.post("{route}", json={const}).json()["id"]',
            f"    changed = {{**{const}, {update_field!r}: {py_literal(update_value)}}}",
            f'    response = client.put(f"{route}/{{item_id}}", json=changed)',
            "    assert response.status_code == 200",
            f"    assert response.json()[{update_field!r}] == {py_literal(update_value)}",
            "",
            "",
            f"def test_{fn}_delete():",
            f'    item_id = client.post("{route}", json={const}).json()["id"]',
            f'    assert client.delete(f"{route}/{{item_id}}").status_code == 204',
            f'    assert client.get(f"{route}/{{item_id}}").status_code == 404',
            "",
            "",
            f"def test_{fn}_not_found():",
            f'    assert client.get("{route}/999999").status_code == 404',
            f'    assert client.put("{route}/999999", json={const}).status_code == 404',
            f'    assert client.delete("{route}/999999").status_code == 404',
            "",
            "",
            f"def test_{fn}_validation_error():",
            f'    assert client.post("{route}", json={{}}).status_code == 422',
        ]
    if include_reports:
        first = entities[0]
        first_payload = f"{snake(first['name']).upper()}_PAYLOAD"
        out += [
            "",
            "",
            "def test_report_summary_counts_records():",
            f'    client.post("{route_for(first["name"])}", json={first_payload})',
            '    response = client.get("/api/reports/summary")',
            "    assert response.status_code == 200",
            f'    assert response.json()["counts"]["{collection_key(first["name"])}"] == 1',
        ]
    return "\n".join(out) + "\n"


def generate_readme(title: str, entities: list[dict[str, Any]], include_reports: bool) -> str:
    rows = "\n".join(
        f"| `{route_for(e['name'])}` | {e['name']} | create, list, get, update, delete |"
        for e in entities
    )
    reports = "\n| `/api/reports/summary` | Reports | record counts |" if include_reports else ""
    return f"""# {title}

Generated by **AgentForge AI** (mock-mode template generator).

A FastAPI service with in-memory storage and an automated pytest suite.

## Run

```bash
python -m venv .venv && source .venv/bin/activate
pip install -r requirements.txt
uvicorn app.main:app --reload     # API docs at http://localhost:8000/docs
python -m pytest                  # run tests
```

## Endpoints

| Path | Resource | Operations |
|------|----------|------------|{chr(10) + rows}{reports}

## Limitations

- In-memory storage: data is lost on restart (replace `app/storage.py` with a database layer).
- Authentication and role-based access are specified in the architecture but not
  implemented in this prototype.
"""


def generate_project(
    title: str, entities: list[dict[str, Any]], include_reports: bool, inject_defect: bool
) -> list[dict[str, Any]]:
    """Return Developer-agent artifacts for a runnable FastAPI service."""
    entity_names = ", ".join(e["name"] for e in entities)
    main_description = f"FastAPI application with CRUD endpoints for {entity_names}."
    if inject_defect:
        main_description += " [MOCK DEMO: contains one intentionally injected defect]"
    files = [
        ("app/__init__.py", "python", "Package marker.", "", []),
        ("app/models.py", "python", "Pydantic request/response models with validation.",
         generate_models(entities), ["pydantic"]),
        ("app/storage.py", "python", "Thread-safe in-memory repository.", STORAGE, []),
        ("app/main.py", "python", main_description,
         generate_main(title, entities, include_reports, inject_defect), ["fastapi"]),
        ("tests/__init__.py", "python", "Package marker.", "", []),
        ("tests/test_api.py", "python", "API, edge-case and validation tests (pytest).",
         generate_tests(entities, include_reports), ["pytest", "httpx"]),
        ("requirements.txt", "text", "Pinned Python dependencies.", SANDBOX_REQUIREMENTS, []),
        ("README.md", "markdown", "How to run and test the generated service.",
         generate_readme(title, entities, include_reports), []),
    ]
    return [
        {
            "file_path": path,
            "file_type": file_type,
            "description": description,
            "content": content,
            "dependencies": deps,
            "proposed_action": "create",
        }
        for path, file_type, description, content, deps in files
    ]
